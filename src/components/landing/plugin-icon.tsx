/** Registry `icon` names (the app's icon set) → lucide equivalents. */
const ICONS: Record<string, LucideIcon> = {
  alarm: AlarmClock,
  ballot: Vote,
  bell: Bell,
  brain: Brain,
  building: Building,
  bus: Bus,
  calendarRange: CalendarRange,
  card: CreditCard,
  catalog: BookOpen,
  chat: MessagesSquare,
  dashboard: LayoutDashboard,
  food: Utensils,
  globe: Globe,
  key: KeyRound,
  library: Library,
  medal: Medal,
  puzzle: Puzzle,
  room: DoorOpen,
  schedule: CalendarDays,
  school: School,
  server: Server,
  sparkles: Sparkles,
  sync: RefreshCw,
  ticket: Ticket,
  timetable: CalendarDays,
  todo: ListTodo,
  wallet: Wallet,
  wand: WandSparkles,
};

export function pluginIcon(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || Puzzle;
}

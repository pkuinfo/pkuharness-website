// Generate the Cloud API reference pages (content/docs/cloud/api/*.mdx) from openapi/cloud-v1.yaml.
// Run with `bun run openapi` after editing the spec; the output is committed.
import { generateFiles } from 'fumadocs-openapi';

import { openapi } from '../src/lib/openapi';

/** First paragraph of a tag description, on one line (frontmatter descriptions feed llms.txt and search). */
const firstParagraph = (text?: string) =>
  text
    ?.trim()
    .split(/\n\s*\n/)[0]
    ?.replace(/\s+/g, ' ');

await generateFiles({
  input: openapi,
  output: './content/docs/cloud/api',
  per: 'tag',
  includeDescription: true,
  frontmatter: (_title, description, context) => ({
    description: firstParagraph(context.type === 'tag' ? context.tag.description : description),
  }),
  addGeneratedComment: 'Generated by `bun run openapi` from openapi/cloud-v1.yaml. Do not edit by hand.',
});

// Generate the Cloud API reference pages from openapi/cloud-v1.yaml, in both site languages:
// `content/docs/cloud/api/<tag>.en.mdx` (English, from the spec) and `<tag>.mdx` (Simplified Chinese:
// same operations, with the page title and description from `zh` below; operation text stays English).
// Run with `bun run openapi` after editing the spec; the output is committed.
import { mkdir, writeFile } from 'node:fs/promises';
import * as path from 'node:path';
import { generateFilesOnly } from 'fumadocs-openapi';

import { openapi } from '../src/lib/openapi';

const output = './content/docs/cloud/api';

/** Chinese page title and description per tag. Keep in step with the tag descriptions in the spec. */
const zh: Record<string, { title: string; description: string }> = {
  meta: {
    title: '元数据',
    description: '服务商发现。用户连接服务商时，宿主会读取它并检查 `protocol`、`services` 和 `limits`。',
  },
  devices: {
    title: '设备与鉴权',
    description:
      '设备的云端身份只有一把 Ed25519 签名密钥和一把 X25519 加密密钥，没有学号，也没有姓名。注册需要完成一次工作量证明；插件 token 由签名质询换取，有效期 10 分钟。',
  },
  store: {
    title: '存储',
    description: '键值存储，命名空间 `(deviceId, plugin)` 取自 token，而不是路径。插件声明了 `e2e` 时，值都是信封。',
  },
  channels: {
    title: '通道（所有者）',
    description:
      '设备开启的端到端加密中继通道，用来和打开分享链接的人实时共享。所有者通过 WebSocket 与对端通信，服务器只转发信封。',
  },
  peers: {
    title: '通道（对端）',
    description:
      '查看方（网页或另一个 App）打开分享链接 `https://<provider>/s/<id>#k=<secret>` 后调用的接口。片段 `k` 不会发到服务器，查看方用它推导出 `authKey` 来加入通道。',
  },
  functions: {
    title: '服务端函数',
    description:
      '插件声明的服务端函数。参考服务器已经实现，但生产配置默认关闭（`CLOUD_FN_POLICY=allowlist`，列表为空），官方服务器也不会开放；自建服务器可以自行开启。',
  },
  push: {
    title: '推送（规划中）',
    description: '推送 token 和定时推送，载荷端到端加密。尚未实现，参考服务器对这些接口返回 `501 unsupported`。',
  },
  pages: {
    title: '分享链接与页面',
    description: '给没装 App 的人用的公开跳转和静态查看页。',
  },
};

/** First paragraph of a tag description, on one line (frontmatter descriptions feed llms.txt and search). */
const firstParagraph = (text?: string) =>
  text
    ?.trim()
    .split(/\n\s*\n/)[0]
    ?.replace(/\s+/g, ' ');

const common = {
  input: openapi,
  per: 'tag',
  includeDescription: true,
  addGeneratedComment: 'Generated by `bun run openapi` from openapi/cloud-v1.yaml. Do not edit by hand.',
} as const;

const english = await generateFilesOnly({
  ...common,
  frontmatter: (_title, description, context) => ({
    description: firstParagraph(context.type === 'tag' ? context.tag.description : description),
  }),
});

const missing = new Set<string>();
const chinese = await generateFilesOnly({
  ...common,
  frontmatter: (_title, description, context) => {
    const tag = context.type === 'tag' ? context.tag.name : undefined;
    const text = tag ? zh[tag] : undefined;
    if (!text) {
      if (tag) missing.add(tag);
      return { description: firstParagraph(context.type === 'tag' ? context.tag.description : description) };
    }
    return { title: text.title, description: text.description };
  },
});
if (missing.size) console.warn(`[openapi] no Chinese title for tag(s): ${[...missing].join(', ')} (English used)`);

const withSuffix = (file: string, suffix: string) => file.replace(/\.mdx$/, suffix);
const files = [
  ...english.map((f) => ({ ...f, path: withSuffix(f.path, '.en.mdx') })),
  ...chinese.map((f) => ({ ...f, path: withSuffix(f.path, '.mdx') })),
];

await Promise.all(
  files.map(async (file) => {
    const filePath = path.join(output, file.path);
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, file.content);
    console.log(`Generated: ${filePath}`);
  }),
);
